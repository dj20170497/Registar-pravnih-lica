    public void osveziTabeluIzBaze() {
        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.vratiZaposlene, null);
        Komunikacija.getInstance().posaljiZahtev(kz);
        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();

        List<Zaposleni> novaLista = (List<Zaposleni>) so.getOdgovor();

        this.zaposleni = novaLista;
        mtz.setLista(novaLista);
        mtz.fireTableDataChanged();
    }

