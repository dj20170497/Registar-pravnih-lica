    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String imeIprezime = jTextField1.getText().trim().toLowerCase();

        List<Zaposleni> filtrirani = new ArrayList<>();

        for (Zaposleni zaposleni1 : zaposleni) {
            String celoIme = (zaposleni1.getIme() + " " + zaposleni1.getPrezime()).toLowerCase();
            if (celoIme.contains(imeIprezime)) {
                filtrirani.add(zaposleni1);
            }

        }
        ModelTabeleZaposleni mt = (ModelTabeleZaposleni) jTable1.getModel();
        mt.setLista(filtrirani);

    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButtonDetaljnijeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDetaljnijeActionPerformed
        int red = jTable1.getSelectedRow();

        if (red == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Izaberite zaposlenog iz tabele.");
            return;
        }

        ModelTabeleZaposleni mt = (ModelTabeleZaposleni) jTable1.getModel();
        Zaposleni z = mt.vratiZaposlenog(red);

        SacuvajZaposlenogForma forma = new SacuvajZaposlenogForma(z, this);
        forma.setVisible(true);
    }//GEN-LAST:event_jButtonDetaljnijeActionPerformed

