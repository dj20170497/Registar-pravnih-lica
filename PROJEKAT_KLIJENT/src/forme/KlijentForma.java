    private void odjaviZaposlenog() {
        try {
            KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.odjava, z);
            Komunikacija.getInstance().posaljiZahtev(kz);

            ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
            boolean odjavljen = (boolean) so.getOdgovor();

            if (!odjavljen) {
                JOptionPane.showMessageDialog(this, "Greška pri odjavi.");
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Greška pri odjavi: " + ex.getMessage());
        }
    }

