    private void jMenuItem1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem1ActionPerformed

        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.vratiMesta, null);
        Komunikacija.getInstance().posaljiZahtev(kz);

//
        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        List<Mesto> mesta = (List<Mesto>) so.getOdgovor();
        if (mesta != null) {

            SacuvajPravnoLiceForma forma = new SacuvajPravnoLiceForma(mesta, z);
            forma.setVisible(true);
        } else {
            JOptionPane.showMessageDialog(this, "ne mogu da povucem mesta iz baze");
        }


    }//GEN-LAST:event_jMenuItem1ActionPerformed

